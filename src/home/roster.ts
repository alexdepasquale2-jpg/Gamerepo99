const KINDS: readonly BuildingKind[] = [
  'outhouse',
  'well',
  'market_stall',
  'farmhouse',
  'bakery',
  'tavern',
  'blacksmith',
  'windmill',
  'church',
  'bullring',
  'aqueduct',
  'castle',
];

function indexRoster(list: readonly BuildingDef[]): Record<BuildingKind, BuildingDef> {
  const map = {} as Record<BuildingKind, BuildingDef>;
  for (const id of KINDS) {
    const def = list.find((d) => d.id === id);
    if (!def) throw new Error(`roster missing ${id}`);
    map[id] = def;
  }
  return map;
}

const BY_KIND = indexRoster(ROSTER);

export function defOf(kind: BuildingKind): BuildingDef {
  return BY_KIND[kind];
}

export function attackOf(kind: BuildingKind, attackId: string): AttackDef | undefined {
  return defOf(kind).attacks.find((a) => a.id === attackId);
}

export function rallyTargets(kind: BuildingKind): readonly BuildingKind[] {
  return defOf(kind).rally;
}

export function playableKinds(): BuildingKind[] {
  return ROSTER.filter((d) => d.playable).map((d) => d.id);
}

export function stubKinds(): BuildingDef[] {
  return ROSTER.filter((d) => !d.playable);
}

export const PACK_MIN = 3;
export const PACK_MAX = 4;

/** Market stalls arrive as a pack of 3 or 4. */
export function packCount(roll: number): number {
  const span = PACK_MAX - PACK_MIN + 1;
  const n = PACK_MIN + Math.floor(roll * span);
  return Math.min(PACK_MAX, Math.max(PACK_MIN, n));
}
